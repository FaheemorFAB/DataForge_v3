"""
DataForge AI - Pydantic Schemas for Structured Outputs & Multi-Agent Communication
"""

from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field

ChartIntent = Literal[
    "bar_chart",
    "line_chart",
    "scatter_chart",
    "histogram",
    "pie_chart",
    "box_plot",
    "table",
    "metric",
    "summary"
]

class AnalysisResult(BaseModel):
    """Structured response expected from AI analysis."""
    code: Optional[str] = Field(
        default=None,
        description="Executable pandas/numpy Python code that computes the result and assigns to `result`."
    )
    answer: str = Field(
        ...,
        description="Clear plain-text answer to the user query with specific figures and findings from data."
    )
    intent: ChartIntent = Field(
        default="summary",
        description="Visual presentation type: bar_chart, line_chart, scatter_chart, histogram, table, metric, or summary."
    )
    x_col: Optional[str] = Field(
        default=None,
        description="Primary categorical or independent column name for chart axis."
    )
    y_col: Optional[str] = Field(
        default=None,
        description="Secondary quantitative or dependent column name for chart axis."
    )
    top_n: Optional[int] = Field(
        default=10,
        description="Limit of items or bars to display in chart or table (default 10)."
    )
    insight: Optional[str] = Field(
        default=None,
        description="Short 1-sentence analytical or business takeaway."
    )

class AgentAction(BaseModel):
    """Telemetry representation of an action taken by a specialized domain agent."""
    agent: str = Field(..., description="Name of the executing agent (e.g., CleanerAgent, AnalyticsAgent).")
    tool: str = Field(..., description="Tool or function executed.")
    status: Literal["running", "completed", "error"] = Field(default="completed")
    message: str = Field(..., description="Human-readable description of what the agent performed.")
    data: Optional[Dict[str, Any]] = Field(default=None, description="Optional payload or summary telemetry.")

class ExecutionPlan(BaseModel):
    """Multi-agent plan generated by the Supervisor."""
    reasoning: str = Field(..., description="Brief rationale of the plan.")
    steps: List[str] = Field(default_factory=list, description="Ordered steps to execute.")
    required_agents: List[str] = Field(default_factory=list, description="List of domain agents to invoke.")

class QueryResponse(BaseModel):
    """Standardized response returned to the workspace chat interface."""
    answer: str
    result: Optional[Dict[str, Any]] = None
    reply: Optional[Dict[str, Any]] = None
    code: Optional[str] = None
    insight: Optional[str] = None
    agent_actions: List[AgentAction] = Field(default_factory=list)
    chat_sessions: Optional[List[Dict[str, Any]]] = None
    active_session_id: Optional[str] = None
